const escapeForScript = (value) => JSON.stringify(value);

export function createServiceWorker({ version, precache }) {
  if (!version) throw new Error('A PWA build version is required');
  // Pages and RSC payloads contain publication state. Never save them offline.
  const safePrecache = [...new Set(precache)].filter((path) => path === '/offline.html' || (!path.endsWith('.html') && !path.endsWith('.rsc') && !path.startsWith('/soundroom/'))).sort();
  return `/* Generated by scripts/build-pwa-assets.mjs. */
const VERSION = ${escapeForScript(version)};
const STATIC_CACHE = \`lowkal-static-\${VERSION}\`;
const PRECACHE = ${JSON.stringify(safePrecache, null, 2)};
const PRECACHE_SET = new Set(PRECACHE);
const isSameOrigin = (url) => url.origin === self.location.origin;
const isRscRequest = (request) => request.headers.get('RSC') === '1';
const isBypassedRequest = (request, url) => request.method !== 'GET' || !isSameOrigin(url) || request.headers.has('Range') || request.destination === 'audio' || request.destination === 'video' || url.pathname.startsWith('/audio/') || url.pathname.startsWith('/api/') || url.pathname.startsWith('/studio');
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(STATIC_CACHE).then((cache) => cache.addAll(PRECACHE)));
});
self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith('lowkal-') && name !== STATIC_CACHE).map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});
self.addEventListener('message', (event) => {
  if (event.data?.type === 'SKIP_WAITING') self.skipWaiting();
});
async function freshDocument(request) {
  try { return await fetch(request, { cache: 'no-store' }); }
  catch { return (await caches.open(STATIC_CACHE)).match('/offline.html').then((response) => response || Response.error()); }
}
async function cacheFirst(request) {
  const cache = await caches.open(STATIC_CACHE);
  const cached = await cache.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (response.ok) await cache.put(request, response.clone());
  return response;
}
self.addEventListener('fetch', (event) => {
  const { request } = event;
  const url = new URL(request.url);
  if (isBypassedRequest(request, url)) return;
  if (isRscRequest(request) || url.pathname.endsWith('.rsc')) {
    event.respondWith(fetch(request, { cache: 'no-store' }));
    return;
  }
  if (request.mode === 'navigate') {
    event.respondWith(freshDocument(request));
    return;
  }
  if (url.pathname.startsWith('/soundroom/')) {
    event.respondWith(fetch(request, { cache: 'no-store' }));
    return;
  }
  if (PRECACHE_SET.has(url.pathname) || url.pathname.startsWith('/_next/static/')) event.respondWith(cacheFirst(request));
});
`;
}
