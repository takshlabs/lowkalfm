const escapeForScript = (value) => JSON.stringify(value);

export function createServiceWorker({ version, precache }) {
  if (!version) throw new Error('A PWA build version is required');
  const safePrecache = [...new Set(precache)].sort();

  return `/* Generated by scripts/build-pwa-assets.mjs. */
const VERSION = ${escapeForScript(version)};
const STATIC_CACHE = \`lowkal-static-\${VERSION}\`;
const DOC_CACHE = \`lowkal-doc-\${VERSION}\`;
const RSC_CACHE = \`lowkal-rsc-\${VERSION}\`;
const IMAGE_CACHE = \`lowkal-images-\${VERSION}\`;
const CACHE_PREFIX = 'lowkal-';
const PRECACHE = ${JSON.stringify(safePrecache, null, 2)};
const PRECACHE_SET = new Set(PRECACHE);

const isSameOrigin = (url) => url.origin === self.location.origin;
const isRscRequest = (request) => request.headers.get('RSC') === '1';
const isBypassedRequest = (request, url) =>
  request.method !== 'GET' ||
  !isSameOrigin(url) ||
  request.headers.has('Range') ||
  request.destination === 'audio' ||
  request.destination === 'video' ||
  url.pathname.startsWith('/audio/') ||
  url.pathname.startsWith('/api/') ||
  url.pathname.startsWith('/studio') ||
  /(?:sanity|youtube|youtu\\.be|googlevideo)/i.test(url.hostname);

const documentFallbackPath = (pathname) => {
  if (pathname === '/') return '/index.html';
  const clean = pathname.replace(/\\/$/, '');
  if (clean.endsWith('.html')) return clean;
  if (PRECACHE_SET.has(\`\${clean}/index.html\`)) return \`\${clean}/index.html\`;
  return \`\${clean}.html\`;
};

const rscFallbackPath = (pathname) => {
  if (pathname === '/') return '/index.rsc';
  const clean = pathname.replace(/\\/$/, '');
  return clean.endsWith('.rsc') ? clean : \`\${clean}.rsc\`;
};

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const staticCache = await caches.open(STATIC_CACHE);
    const documentCache = await caches.open(DOC_CACHE);
    const rscCache = await caches.open(RSC_CACHE);
    const staticUrls = PRECACHE.filter((path) => !path.endsWith('.html') && !path.endsWith('.rsc'));
    const documentUrls = PRECACHE.filter((path) => path.endsWith('.html'));
    const rscUrls = PRECACHE.filter((path) => path.endsWith('.rsc'));
    await Promise.all([
      staticCache.addAll(staticUrls),
      documentCache.addAll(documentUrls),
      rscCache.addAll(rscUrls),
    ]);
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const active = new Set([STATIC_CACHE, DOC_CACHE, RSC_CACHE, IMAGE_CACHE]);
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith(CACHE_PREFIX) && !active.has(name)).map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data?.type === 'SKIP_WAITING') self.skipWaiting();
});

async function networkFirstDocument(request, url) {
  const cache = await caches.open(DOC_CACHE);
  try {
    const response = await fetch(request);
    if (response.ok) await cache.put(documentFallbackPath(url.pathname), response.clone());
    return response;
  } catch {
    return (await cache.match(documentFallbackPath(url.pathname))) || (await cache.match('/offline.html')) || Response.error();
  }
}

async function networkFirstRsc(request, url) {
  const cache = await caches.open(RSC_CACHE);
  try {
    const response = await fetch(request);
    if (response.ok) await cache.put(rscFallbackPath(url.pathname), response.clone());
    return response;
  } catch {
    return (await cache.match(rscFallbackPath(url.pathname))) || Response.error();
  }
}

async function cacheFirst(request) {
  const cache = await caches.open(STATIC_CACHE);
  const cached = await cache.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (response.ok) await cache.put(request, response.clone());
  return response;
}

async function staleWhileRevalidate(request) {
  const cache = await caches.open(IMAGE_CACHE);
  const cached = await cache.match(request);
  const network = fetch(request).then(async (response) => {
    if (response.ok) await cache.put(request, response.clone());
    return response;
  }).catch(() => null);
  return cached || (await network) || Response.error();
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  const url = new URL(request.url);
  if (isBypassedRequest(request, url)) return;
  if (isRscRequest(request)) {
    event.respondWith(networkFirstRsc(request, url));
    return;
  }
  if (request.mode === 'navigate') {
    event.respondWith(networkFirstDocument(request, url));
    return;
  }
  if (PRECACHE_SET.has(url.pathname)) {
    event.respondWith(cacheFirst(request));
    return;
  }
  if (request.destination === 'image') {
    event.respondWith(staleWhileRevalidate(request));
    return;
  }
  if (url.pathname.startsWith('/_next/static/') || /\\.[a-f0-9]{8,}\\.(?:js|css)$/i.test(url.pathname)) {
    event.respondWith(cacheFirst(request));
  }
});
`;
}
